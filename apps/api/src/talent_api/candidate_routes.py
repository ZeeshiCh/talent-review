"""Swagger-documented candidate endpoints, scoped only by personal bearer links."""

import re
from typing import Annotated
from uuid import UUID

from fastapi import APIRouter, Depends, File, Header, HTTPException, Response, UploadFile
from fastapi.security import HTTPAuthorizationCredentials, HTTPBearer
from sqlalchemy.orm import Session

from .candidate_schemas import InterviewPublic, Progress, QuestionPublic, Receipt, TextSubmission
from .candidate_service import (
    audio_payload,
    authorize,
    get_interview,
    scoped_question,
    submit,
    text_payload,
)
from .config import Settings, settings
from .db import get_db

router = APIRouter(
    prefix="/candidate",
    tags=["Candidate"],
    responses={
        401: {"description": "Missing, invalid, expired, or revoked personal link"},
        403: {"description": "Interview is unavailable"},
        503: {"description": "Database, questions, or private storage temporarily unavailable"},
    },
)
bearer = HTTPBearer(
    auto_error=False,
    scheme_name="CandidateLink",
    description="Personal invitation token. Paste the token only, without the word Bearer. Generated by the trusted candidate:invite CLI.",
)


def get_settings() -> Settings:
    return settings


def candidate_token(
    credentials: Annotated[HTTPAuthorizationCredentials | None, Depends(bearer)],
) -> str:
    if (
        credentials is None
        or credentials.scheme.lower() != "bearer"
        or not re.fullmatch(r"[A-Za-z0-9_-]{43}", credentials.credentials)
    ):
        raise HTTPException(
            401,
            "A valid personal-link bearer token is required",
            headers={"WWW-Authenticate": "Bearer"},
        )
    return credentials.credentials


Token = Annotated[str, Depends(candidate_token)]
Database = Annotated[Session, Depends(get_db)]
Config = Annotated[Settings, Depends(get_settings)]
IdempotencyKey = Annotated[
    str,
    Header(
        alias="Idempotency-Key",
        min_length=1,
        max_length=200,
        pattern=r"^[!-~]+$",
        description="Unique request key. Reuse this exact key when retrying the same answer.",
    ),
]


@router.get(
    "/interview", response_model=InterviewPublic, summary="Open your interview and resume progress"
)
def interview(token: Token, db: Database) -> InterviewPublic:
    return get_interview(db, token)


@router.get(
    "/progress",
    response_model=Progress,
    summary="Reload persisted submission receipts and the next question",
)
def progress(token: Token, db: Database) -> Progress:
    return get_interview(db, token).progress


@router.get(
    "/questions/{question_id}",
    response_model=QuestionPublic,
    summary="Read one question belonging to your interview",
)
def question(question_id: UUID, token: Token, db: Database) -> QuestionPublic:
    with db.begin():
        access = authorize(db, token)
        q = scoped_question(db, access, question_id)
        return QuestionPublic(id=q.id, number=q.position, prompt=q.prompt)


@router.post(
    "/questions/{question_id}/answer",
    response_model=Receipt,
    status_code=201,
    responses={
        200: {"model": Receipt, "description": "Previously accepted answer; same durable receipt"},
        401: {"description": "Invalid, revoked, or expired link"},
        404: {"description": "Question outside this interview"},
        409: {
            "description": "Changed payload/key reuse, accepted answer, or out-of-order question"
        },
    },
    summary="Submit a typed answer exactly once",
)
def answer(
    question_id: UUID,
    body: TextSubmission,
    token: Token,
    key: IdempotencyKey,
    db: Database,
    config: Config,
    response: Response,
) -> Receipt:
    result, created = submit(db, token, question_id, key, text_payload(body.text), config)
    response.status_code = 201 if created else 200
    return result


@router.post(
    "/questions/{question_id}/audio",
    response_model=Receipt,
    status_code=201,
    responses={
        200: {"model": Receipt, "description": "Previously accepted upload; same durable receipt"},
        401: {"description": "Invalid, revoked, or expired link"},
        404: {"description": "Question outside this interview"},
        409: {
            "description": "Changed payload/key reuse, accepted answer, or out-of-order question"
        },
        413: {"description": "Upload exceeds the size limit"},
        415: {"description": "Unsupported, invalid, or mismatched audio type"},
    },
    summary="Upload a private M4A, MP3, or WAV answer",
)
def audio(
    question_id: UUID,
    token: Token,
    key: IdempotencyKey,
    db: Database,
    config: Config,
    response: Response,
    file: Annotated[
        UploadFile,
        File(
            description="Audio file, up to 20 MiB by default. Stored privately; transcription is not implemented."
        ),
    ],
) -> Receipt:
    try:
        # Reject invalid access before decoding or storing an upload.
        with db.begin():
            scoped_question(db, authorize(db, token), question_id)
        data = file.file.read(config.candidate_max_audio_bytes + 1)
        payload = audio_payload(data, file.content_type, config)
        result, created = submit(db, token, question_id, key, payload, config)
        response.status_code = 201 if created else 200
        return result
    finally:
        file.file.close()
